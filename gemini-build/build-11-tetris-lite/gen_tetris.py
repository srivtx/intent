#!/usr/bin/env python3
"""
Generates tetris.intent.

WHY A GENERATOR: Intent 0.6 has no arrays, no loops over numbers, and no "per group"
summaries (count of cells per row). A row that fills up must therefore be tracked by one
single value per row (fill1 .. fillH), and clearing row K must shift every counter above it
by hand. That is O(H^2) sentences, which nobody should type. This file is itself one of
the findings of this experiment: the program is ~150 sentences of near-identical English.
"""
import os

W, H = 8, 14
# Bug found: "The fill2 starts at 0." after "The fill1 starts at 0." is refused as a misspelling
# of fill1 ("did you mean fill1?"), even though it is a declaration. Names that differ by one
# character cannot coexist. So rows get NATO-alphabet names instead of numbers.
NATO = ["alpha", "bravo", "charlie", "delta", "echo", "foxtrot", "golf", "hotel", "india",
        "juliet", "kilo", "lima", "mike", "november", "oscar", "papa", "quebec", "romeo"]
def fill(k):
    return NATO[k - 1]
out = []
s = out.append

s(f"""# Tetris-lite (falling single blocks, rows clear), in Intent v0.6.0.
# GENERATED by gen_tetris.py - edit that file, not this one.
#   ./intent build gemini-build/build-11-tetris-lite/tetris.intent -o build/tetris && build/tetris
# Left/right move the block, down drops it faster. A full row disappears.

The board is {W} wide and {H} high.

The px starts at 4.
The py starts at 1.
The landed starts at 0.
The clear starts at 0.
The clock starts at 0.
The score starts at 0.
The lines start at 0.
The delay starts at 8.
""")
for k in range(1, H + 1):
    s(f"The {fill(k)} starts at 0.")
s("""
Cells is a collection where each cell has an x (number) and a y (number).

# --- gravity gets faster as rows are cleared (timers are fixed, so a fast clock counts up to a delay)
The delay is always 2 if the lines are at least 18, otherwise 8 minus the lines divided by 3.
Every 50 milliseconds, the clock increases by 1.

# --- moving
# Bug found: "if the px is over 1 and no cell has ..." is refused ("I don't know the word no");
# "any"/"no" only work as the FIRST condition, so the order of the two conditions is forced.
When the left key is pressed, if no cell has an x equal to the px minus 1 and a y equal to the py, the px decreases by 1 if the px is over 1.
When the right key is pressed, if no cell has an x equal to the px plus 1 and a y equal to the py, the px increases by 1 if the px is under %(W)d.
When the down key is pressed, the clock becomes the delay.

# --- one step of gravity, in order
Every 50 milliseconds, if the clock is at least the delay and the py is %(H)d, the landed becomes 1.
Every 50 milliseconds, if any cell has an x equal to the px and a y equal to the py plus 1, the landed becomes 1 if the clock is at least the delay.
Every 50 milliseconds, if the clock is at least the delay and the landed is 0, the py increases by 1.
""" % {"W": W, "H": H})
for k in range(1, H + 1):
    s(f"Every 50 milliseconds, if the landed is 1 and the py is {k}, the {fill(k)} increases by 1.")
s("Every 50 milliseconds, if the landed is 1, add a cell whose x is the px and whose y is the py.")
s("Every 50 milliseconds, if the landed is 1, the px becomes a random number between 1 and %d." % W)
s("Every 50 milliseconds, if the landed is 1, the py becomes 1.")
s("Every 50 milliseconds, if the landed is 1, the score increases by 1.")
s("Every 50 milliseconds, if the landed is 1, the landed becomes 0.")
s("Every 50 milliseconds, if the clock is at least the delay, the clock becomes 0.")
s("\n# --- a full row: remember which, then remove it, drop everything above, shift the counters")
for k in range(1, H + 1):
    s(f"Every 50 milliseconds, if the {fill(k)} is {W}, the clear becomes {k}.")
for k in range(1, H + 1):
    # 0.6 refuses "if X, remove the Ys whose ..." but accepts the same condition at the end.
    # And in "increase the y of the cells whose ... by 1 if ...", parser.py:1830 slices from "by"
    # to the end of the sentence into main, swallowing the trailing "if ..."! Putting "by 1"
    # before "if" avoids that slice.
    s(f"Every 50 milliseconds, remove the cells whose y is {k} if the clear is {k}.")
    s(f"Every 50 milliseconds, increase each cell's y by 1 if its y is under {k} and the clear is {k}.")
    for j in range(k, 1, -1):
        s(f"Every 50 milliseconds, if the clear is {k}, the {fill(j)} becomes the {fill(j - 1)}.")
    s(f"Every 50 milliseconds, if the clear is {k}, the {fill(1)} becomes 0.")
s("Every 50 milliseconds, if the clear is over 0, the lines increase by 1.")
s("Every 50 milliseconds, if the clear is over 0, the score increases by 100.")
s("Every 50 milliseconds, if the clear is over 0, the clear becomes 0.")
s("""
The game is over when any cell has a y under 2.

Draw each cell at its x and its y as a cyan "#".
Draw a yellow "@" at the px and the py.
Show the score and the lines above the board.
""")

here = os.path.dirname(os.path.abspath(__file__))
path = os.path.join(here, "tetris.intent")
with open(path, "w") as f:
    f.write("\n".join(out))
n = sum(1 for line in out for part in line.split("\n") if part.strip() and not part.startswith("#"))
print(f"wrote {path}: {n} sentences")
